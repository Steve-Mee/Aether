export function filterDemoByPeriod(
  items: ActivityItem[],
  period: ActivityPeriod,
  custom?: { from: string; to: string },
): ActivityItem[] {
  const now = new Date();
  let since: Date;
  if (period === 'custom' && custom?.from) {
    since = new Date(custom.from);
  } else if (period === 'today') {
    since = new Date();
    since.setHours(0, 0, 0, 0);
  } else {
    since = new Date();
    since.setDate(since.getDate() - periodToDays(period));
    since.setHours(0, 0, 0, 0);
  }
  const until = period === 'custom' && custom?.to ? new Date(custom.to) : now;
  return items.filter((i) => {
    const d = new Date(i.at);
    return d >= since && d <= until;
  });
}
