import type { ActivityItem, ActivityPeriod } from '@/types/activity';

function daysAgo(days: number, hour = 10, minute = 0): string {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

function item(partial: Omit<ActivityItem, 'source' | 'searchText'> & { id: string }): ActivityItem {
  const searchText = [
    partial.actionLabel,
    partial.description,
    partial.module,
    partial.actionType,
    partial.impact?.value,
    partial.details?.productName,
    partial.details?.supplierName,
  ]
    .filter(Boolean)
    .join(' ')
    .toLowerCase();
  return { ...partial, source: 'demo', searchText };
}

